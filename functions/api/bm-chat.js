function json(data, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store' }
  });
}

function clean(messages) {
  if (!Array.isArray(messages) || !messages.length || messages.length > MAX_MESSAGES) return null;
  let total = 0;
  const out = [];
  for (const m of messages) {
    if (!m || (m.role !== 'user' && m.role !== 'assistant') || typeof m.content !== 'string') return null;
    const c = m.content.slice(0, m.role === 'user' ? MAX_CHARS : 12000);
    total += c.length;
    out.push({ role: m.role, content: c });
  }
  if (total > MAX_TOTAL || out[out.length - 1].role !== 'user') return null;
  // Модели нужен первый ход от участника: сайт сам показал первый вопрос
  if (out[0].role === 'assistant') out.unshift({ role: 'user', content: 'Начать диагностику' });
  return out;
}

async function askClaude(env, messages) {
  const r = await fetch('https://api.anthropic.com/v1/messages', {
    method: 'POST',
    headers: { 'x-api-key': env.ANTHROPIC_API_KEY, 'anthropic-version': '2023-06-01', 'content-type': 'application/json' },
    body: JSON.stringify({
      model: env.BM_MODEL || 'claude-sonnet-5-5',
      max_tokens: 4000,
      temperature: 0.3,
      // кеш промпта: длинная инструкция оплачивается полностью один раз, дальше — со скидкой
      system: [{ type: 'text', text: SYSTEM, cache_control: { type: 'ephemeral' } }],
      messages
    })
  });
  const d = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error('claude ' + r.status + ' ' + JSON.stringify(d).slice(0, 300));
  return (d.content || []).filter(b => b.type === 'text').map(b => b.text).join('');
}

async function askOpenAI(env, messages) {
  const r = await fetch('https://api.openai.com/v1/chat/completions', {
    method: 'POST',
    headers: { Authorization: 'Bearer ' + env.OPENAI_API_KEY, 'content-type': 'application/json' },
    body: JSON.stringify({
      model: env.BM_MODEL || 'gpt-4.1-mini',
      max_tokens: 4000,
      temperature: 0.3,
      messages: [{ role: 'system', content: SYSTEM }].concat(messages)
    })
  });
  const d = await r.json().catch(() => ({}));
  if (!r.ok) throw new Error('openai ' + r.status + ' ' + JSON.stringify(d).slice(0, 300));
  return ((d.choices || [])[0] || {}).message?.content || '';
}

export async function onRequestPost({ request, env }) {
  if (!env.ANTHROPIC_API_KEY && !env.OPENAI_API_KEY) return json({ error: 'no_key' }, 503);
  let body;
  try { body = await request.json(); } catch (e) { return json({ error: 'bad_json' }, 400); }
  const messages = clean(body && body.messages);
  if (!messages) return json({ error: 'bad_messages' }, 400);
  try {
    const reply = env.ANTHROPIC_API_KEY ? await askClaude(env, messages) : await askOpenAI(env, messages);
    if (!reply.trim()) return json({ error: 'empty' }, 502);
    return json({ reply });
  } catch (e) {
    console.log('bm-chat error', String(e));
    return json({ error: 'ai_failed' }, 502);
  }
}

export function onRequestGet({ env }) {
  return json({ ok: true, ai: !!(env.ANTHROPIC_API_KEY || env.OPENAI_API_KEY) });
}
